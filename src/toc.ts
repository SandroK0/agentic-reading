import type { PDFDocumentProxy } from "pdfjs-dist";
import type { ContentsEntry } from "../shared/types";

/**
 * The Contents sidebar. It shows the PDF's own outline (its bookmarks) when
 * there is one. Otherwise it offers to generate a table of contents with the
 * model, shows a saved one the same way, and lets you regenerate or remove
 * it. Entries jump to their page, and the section you're reading stays highlighted.
 */

interface OutlineNode {
  title: string;
  dest: string | unknown[] | null;
  items: OutlineNode[];
}

/** A contents entry with its page resolved, from either source. */
interface Node {
  title: string;
  page: number | null;
  items: Node[];
}

interface Entry {
  page: number | null;
  link: HTMLButtonElement;
  /** Collapsible <li>s from the root down to this entry (inclusive when it has children). */
  branches: HTMLLIElement[];
}

/** How generated contents are made and forgotten; supplied by the app, which knows the open book. */
export interface ContentsGeneration {
  /** Builds and saves contents for the open book, reporting progress as short sentences. */
  generate(onProgress: (text: string) => void, signal: AbortSignal): Promise<ContentsEntry[]>;
  remove(): Promise<void>;
}

/** Top levels with more entries than this start collapsed. */
const EXPAND_TOP_LEVEL_UP_TO = 10;

export class Contents {
  private entries: Entry[] = [];
  private active: Entry | null = null;
  private loadToken = 0;
  private currentPage = 1;
  private generated: ContentsEntry[] | null = null;
  private generating: AbortController | null = null;

  constructor(
    private body: HTMLElement,
    private go: (page: number) => void,
    private generation: ContentsGeneration,
  ) {}

  /** Shows the book's outline, or its saved generated contents, or the offer to generate some. */
  async load(doc: PDFDocumentProxy, generated?: ContentsEntry[]) {
    const token = ++this.loadToken;
    this.generating?.abort();
    this.generating = null;
    this.generated = generated?.length ? generated : null;
    this.reset();
    this.body.replaceChildren(this.message("Loading contents…"));

    const outline = ((await doc.getOutline().catch(() => null)) ?? []) as OutlineNode[];
    const nodes = await resolveOutline(doc, outline);
    if (token !== this.loadToken) return;

    if (nodes.length) this.show(nodes);
    else if (this.generated) this.showGenerated(this.generated);
    else this.showOffer();
  }

  /** Highlights the last section that starts at or before `page`. */
  setPage(page: number) {
    this.currentPage = page;
    let best: Entry | null = null;
    for (const entry of this.entries) {
      if (entry.page !== null && entry.page <= page && (!best || entry.page >= best.page!)) best = entry;
    }
    if (best === this.active) return;
    this.active?.link.classList.remove("active");
    this.active = best;
    if (!best) return;
    best.link.classList.add("active");
    for (const li of best.branches) setOpen(li, true);
    best.link.scrollIntoView({ block: "nearest" });
  }

  private reset() {
    this.entries = [];
    this.active = null;
  }

  private show(nodes: Node[], header?: HTMLElement) {
    this.reset();
    const expandTop = nodes.length <= EXPAND_TOP_LEVEL_UP_TO;
    this.body.replaceChildren(...(header ? [header] : []), this.list(nodes, [], expandTop));
    this.setPage(this.currentPage);
  }

  private showGenerated(entries: ContentsEntry[], note?: string) {
    const header = document.createElement("div");
    header.className = "toc-generated";
    const label = document.createElement("span");
    label.textContent = note ?? "Generated by AI";
    if (note) label.className = "toc-error";
    const regenerate = this.button("Regenerate", () => void this.generate());
    const remove = this.button("Remove", () => void this.remove());
    header.append(label, regenerate, remove);
    this.show(nestEntries(entries), header);
  }

  private showOffer(error?: string) {
    this.reset();
    const offer = document.createElement("div");
    offer.className = "toc-offer";
    const text = this.message("This PDF has no table of contents.");
    const button = this.button("Generate with AI", () => void this.generate());
    button.classList.add("primary");
    const hint = document.createElement("p");
    hint.className = "toc-hint";
    hint.textContent = "Reads the book's headings and any printed contents page. Takes a minute or two.";
    offer.append(text, button, hint);
    if (error) offer.append(this.message(error, "toc-error"));
    this.body.replaceChildren(offer);
  }

  private async generate() {
    const token = this.loadToken;
    this.generating?.abort();
    const controller = new AbortController();
    this.generating = controller;

    const progress = this.message("Starting…");
    const cancel = this.button("Cancel", () => controller.abort());
    const panel = document.createElement("div");
    panel.className = "toc-offer";
    panel.append(progress, cancel);
    this.reset();
    this.body.replaceChildren(panel);

    try {
      const entries = await this.generation.generate((text) => (progress.textContent = text), controller.signal);
      if (token !== this.loadToken || controller.signal.aborted) return;
      this.generated = entries;
      this.showGenerated(entries);
    } catch (err) {
      if (token !== this.loadToken) return;
      const message = controller.signal.aborted ? undefined : (err as Error).message;
      // A failed regenerate keeps the contents you already had.
      if (this.generated) this.showGenerated(this.generated, message && `Couldn't regenerate: ${message}`);
      else this.showOffer(message);
    } finally {
      if (this.generating === controller) this.generating = null;
    }
  }

  private async remove() {
    if (!confirm("Remove the generated table of contents? You can generate it again later.")) return;
    await this.generation.remove();
    this.generated = null;
    this.showOffer();
  }

  private list(nodes: Node[], parents: HTMLLIElement[], open: boolean): HTMLUListElement {
    const ul = document.createElement("ul");
    for (const node of nodes) {
      const li = document.createElement("li");
      const row = document.createElement("div");
      row.className = "toc-row";

      const twisty = document.createElement("button");
      twisty.className = "toc-twisty";
      const link = document.createElement("button");
      link.className = "toc-link";
      const title = document.createElement("span");
      title.textContent = node.title.trim() || "Untitled";
      const pageLabel = document.createElement("span");
      pageLabel.className = "toc-page";
      pageLabel.textContent = node.page ? String(node.page) : "";
      link.append(title, pageLabel);
      link.title = node.title.trim();
      const page = node.page;
      if (page) link.onclick = () => this.go(page);
      else link.disabled = true;
      row.append(twisty, link);
      li.append(row);

      const branches = node.items.length ? [...parents, li] : parents;
      this.entries.push({ page, link, branches });

      if (node.items.length) {
        li.append(this.list(node.items, branches, false));
        twisty.setAttribute("aria-label", `Expand ${title.textContent}`);
        twisty.onclick = () => setOpen(li, !li.classList.contains("open"));
        setOpen(li, open);
      } else {
        twisty.classList.add("leaf");
        twisty.tabIndex = -1;
      }
      ul.append(li);
    }
    return ul;
  }

  private button(label: string, onClick: () => void) {
    const b = document.createElement("button");
    b.textContent = label;
    b.onclick = onClick;
    return b;
  }

  private message(text: string, className = "toc-empty") {
    const p = document.createElement("p");
    p.className = className;
    p.textContent = text;
    return p;
  }
}

function setOpen(li: HTMLLIElement, open: boolean) {
  const child = li.querySelector(":scope > ul") as HTMLElement | null;
  const twisty = li.querySelector(":scope > .toc-row > .toc-twisty") as HTMLElement | null;
  if (!child || !twisty) return;
  li.classList.toggle("open", open);
  child.hidden = !open;
  twisty.textContent = open ? "▾" : "▸";
  twisty.setAttribute("aria-expanded", String(open));
}

/** Turns a flat, levelled list into a tree: each entry nests under the nearest shallower one before it. */
function nestEntries(entries: ContentsEntry[]): Node[] {
  const roots: Node[] = [];
  const stack: { level: number; node: Node }[] = [];
  for (const entry of entries) {
    const node: Node = { title: entry.title, page: entry.page, items: [] };
    while (stack.length && stack[stack.length - 1].level >= entry.level) stack.pop();
    (stack.length ? stack[stack.length - 1].node.items : roots).push(node);
    stack.push({ level: entry.level, node });
  }
  return roots;
}

async function resolveOutline(doc: PDFDocumentProxy, outline: OutlineNode[]): Promise<Node[]> {
  return Promise.all(
    outline.map(async (n) => ({ title: n.title, page: await pageOf(doc, n.dest), items: await resolveOutline(doc, n.items ?? []) })),
  );
}

/** Resolves an outline destination (named or explicit) to a 1-based page. */
async function pageOf(doc: PDFDocumentProxy, dest: OutlineNode["dest"]): Promise<number | null> {
  try {
    const explicit = typeof dest === "string" ? await doc.getDestination(dest) : dest;
    const ref = Array.isArray(explicit) ? explicit[0] : null;
    if (typeof ref === "number") return ref + 1;
    if (ref && typeof ref === "object") return (await doc.getPageIndex(ref as never)) + 1;
  } catch {
    // broken destination: leave the entry without a page
  }
  return null;
}
